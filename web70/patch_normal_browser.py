#!/usr/bin/env python3
"""Convert the visually tested v69 guest into a normal user-controlled browser.

Only the compressed RAM-root changes. Preserve kernel, initrd, Firefox binary,
valid root CA certificates and existing non-root browser account.
Remove the v69 timed demo, install an accessible home launchpad and a truthful
file:// status page generated by the existing HTTPS diagnostic.
"""
import argparse
import json
from pathlib import Path

NAV_START="# v69 test: preserve the original local page and click/key proof."
NAV_END=") &\n"
FIREFOX_COMMAND="su -s /bin/sh web -c 'DISPLAY=:0 XAUTHORITY=/home/web/.Xauthority HOME=/home/web firefox-esr file:///usr/share/puppy50web/index.html' >/var/log/firefox.log 2>&1"

def patch(root):
    root=Path(root)
    session=root/"usr/local/bin/puppy50-web-launch"
    probe=root/"usr/local/bin/puppy50-network-probe"
    core=root/"usr/local/libexec/puppy50-network-probe-core"
    home=root/"usr/share/puppy50web/index.html"
    ca=root/"etc/ssl/certs/ca-certificates.crt"
    firefox=root/"usr/lib/firefox-esr/firefox"
    for p in (session,probe,home,ca,firefox):
        if not p.is_file():
            raise ValueError("Required tested guest file missing: "+str(p))
    old=session.read_text()
    if old.count(NAV_START)!=1 or old.count(FIREFOX_COMMAND)!=1:
        raise ValueError("Native demo or original Firefox launch has changed")
    begin=old.index(NAV_START)
    end=old.find(NAV_END,begin)
    if end<0:raise ValueError("Native demo end marker missing")
    end+=len(NAV_END)
    removed=old[begin:end]
    if "PUPPY50_V69_NATIVE_FIREFOX_NAV_REQUESTED" not in removed or "sleep 205" not in removed:
        raise ValueError("Not the documented v69 native navigation demo")
    new=old[:begin]+old[end:]
    if "PUPPY50_V69_NATIVE_FIREFOX_NAV" in new:
        raise ValueError("Automatic public-site demo was not completely removed")
    if new.count(FIREFOX_COMMAND)!=1:
        raise ValueError("Normal Firefox startup not preserved")
    session.write_text(new);session.chmod(0o755)

    # Preserve the previously proven networking core; extend only with a
    # transparent, local, fixed-text status report for the user.
    core.parent.mkdir(parents=True,exist_ok=True)
    core.write_bytes(probe.read_bytes());core.chmod(0o755)
    wrapper=Path(__file__).with_name("network_status_wrapper.sh")
    probe.write_bytes(wrapper.read_bytes());probe.chmod(0o755)
    page=Path(__file__).with_name("launchpad.html").read_bytes()
    home.write_bytes(page);home.chmod(0o644)
    return {"schema":"PUPPY50_V70_NORMAL_BROWSING_ROOT_PATCH",
      "automated_external_site_navigation_removed":True,
      "original_non_root_firefox_launcher_preserved":True,
      "original_CA_bundle_preserved":True,
      "original_guest_network_probe_preserved_as_core":True,
      "dynamic_guest_network_status_page_added":True,
      "user_can_choose_websites_from_homepage_or_addressbar":True,
      "no_browser_security_or_TLS_bypass":True,
      "kernel_and_initrd_modified":False}

if __name__=="__main__":
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument("root",type=Path)
    print(json.dumps(patch(ap.parse_args().root),indent=2))
